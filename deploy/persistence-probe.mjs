// Executed only inside the new network-disabled QA container by smoke-persistence.mjs.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { PiBotClient } from '../src/sdk/client.ts';

const phase = process.argv[2];
assert.ok(['write', 'verify'].includes(phase));
const runtime = '/data/runtime';
let discovery;
for (let i = 0; i < 150; i++) {
  try {
    discovery = JSON.parse(readFileSync(runtime + '/daemon.json', 'utf8'));
    assert.equal(discovery.http, 'http://127.0.0.1:4318');
    if ((await fetch(discovery.http + '/readyz', { signal: AbortSignal.timeout(1000) })).ok) break;
  } catch { /* Startup only; do not modify discovery or authentication. */ }
  discovery = undefined;
  await new Promise(r => setTimeout(r, 100));
}
assert.ok(discovery, 'real harness must become ready');
// Generated by THIS disposable QA harness, never displayed or persisted in evidence.
const client = await PiBotClient.connect({ transport: {
  http: discovery.http, token: readFileSync(runtime + '/daemon.token', 'utf8').trim()
} });
try {
  const status = await client.daemon.status({});
  assert.equal(status.status, 'ready');
  assert.equal(status.model.setupRequired, true);
  assert.notEqual(status.model.id, 'test');
  const text = 'Synthetic persistence QA; no provider credentials or model calls.';
  let fixture;
  if (phase === 'write') {
    const { bot } = await client.bot.create({ name: 'Synthetic persistence QA', key: 'persistence-qa-bot' });
    await client.bot.update({ botId: bot.id, description: text });
    fixture = { botId: bot.id, description: text, firstStartedAt: status.startedAt };
    writeFileSync('/data/qa-fixture.json', JSON.stringify(fixture), { flag: 'wx', mode: 0o600 });
    writeFileSync('/data/workspace/persistence-check.txt', text, { flag: 'wx', mode: 0o600 });
  } else {
    fixture = JSON.parse(readFileSync('/data/qa-fixture.json', 'utf8'));
    assert.notEqual(status.startedAt, fixture.firstStartedAt, 'a new daemon process must have started');
    assert.equal(readFileSync('/data/workspace/persistence-check.txt', 'utf8'), text);
  }
  const { bot } = await client.bot.read({ botId: fixture.botId });
  assert.equal(bot.name, 'Synthetic persistence QA');
  assert.equal(bot.description, fixture.description);
  let missingModel;
  await assert.rejects(client.turn.start({ botId: bot.id, text: 'Synthetic missing-model rejection check', key: 'persistence-qa-' + phase }), error => {
    missingModel = { reason: error.reason, message: error.message, retryable: error.retryable };
    return error.reason === 'setupRequired' && error.retryable === false;
  });
  const snapshot = await client.daemon.snapshot({});
  assert.match(snapshot.mode, /^真实 Pi/);
  assert.equal(snapshot.bots.length, 1);
  assert.equal(snapshot.turns.length, 0, 'guard must reject the turn, not create a fake conversation');
  assert.equal(snapshot.usage.totalTokens, 0);
  assert.equal(snapshot.usage.costUsd, 0);
  console.log(JSON.stringify({ phase, ready: true, mode: snapshot.mode, botId: bot.id,
    descriptionPreserved: true, workspaceFilePreserved: true, startedAt: status.startedAt,
    missingModel, turns: snapshot.turns.length, totalTokens: 0, costUsd: 0 }));
} finally { client.close(); }

"""Browser QA against serve.mjs only. Synthetic data; never a production runtime."""
import subprocess, json, time
from pathlib import Path
out=Path('artifacts/astra');out.mkdir(parents=True,exist_ok=True)
checks=[]
base='http://127.0.0.1:5193/clients/tauri/test/ui/index.html'
def ab(*args):
 r=subprocess.run(['agent-browser','--session','pibo-astra','--json',*args],capture_output=True,text=True)
 if r.returncode: raise RuntimeError(r.stderr or r.stdout)
 data=json.loads(r.stdout)
 if not data.get('success'):raise RuntimeError(data)
 return data.get('data',{})
def js(code):return ab('eval',code).get('result')
def wait():time.sleep(.35)
def click(name,role='button'):ab('find','role',role,'click','--name',name);wait()
def openq(query):ab('open',base+'?'+query);wait()
def shot(name):ab('screenshot',str(out/name))
def check(name,value):
 checks.append({'check':name,'pass':bool(value)})
 (out/'browser-checks.json').write_text(json.dumps(checks,ensure_ascii=False,indent=2))
 if not value:raise AssertionError(name)
def rect(selector):return js(f'document.querySelector({json.dumps(selector)}).getBoundingClientRect().toJSON()')
def chat():
 ab('wait','[aria-label="灵感搭子 · 演示"]');ab('scrollintoview','[aria-label="灵感搭子 · 演示"]');ab('click','[aria-label="灵感搭子 · 演示"]');wait()
 check('Chat route opened',js('document.querySelector(".app").dataset.phonePage')=='chat')
q='phone=1&connected=1&models=1&story=1'

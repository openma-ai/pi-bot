before=rect('.conversation');click('添加附件');menu=rect('[role=menu]');shell=rect('.composer-shell')
check('Menu opens above entire multiline composer',menu['bottom']<=shell['top']-6)
check('Menu leaves conversation geometry unchanged',before==rect('.conversation'))
shot('09-menu-multiline-phone.png');ab('press','Escape')
# VisualViewport CSS override models an on-screen keyboard without pretending to be native iOS.
js('document.documentElement.style.setProperty("--phone-height","390px");document.documentElement.style.setProperty("--phone-bottom-inset","0px")');wait()
check('Keyboard: composer within visible 390px',rect('.composer-shell')['bottom']<=390)
check('Keyboard: page origin stable',js('scrollY')==0)
shot('10-keyboard-chat-simulation.png')
js('window.dispatchEvent(new Event("resize"))');wait()
check('Keyboard dismissal restores composer',rect('.composer-shell')['bottom']>800)
click('返回会话列表');click('新建会话');click('新建 bot','menuitem')
check('Blank bot name disabled',js('[...document.querySelectorAll("button")].find(e=>e.textContent==="创建").disabled'))
ab('fill','[aria-label="名称"]','取消的测试 bot');click('取消')
check('Cancel does not create bot',js('window.__PIBO_TEST__.botCreates')==0)
click('新建会话');click('新建 bot','menuitem');ab('fill','[aria-label="名称"]','重复点击测试 '+str(int(time.time())))
js('document.documentElement.style.setProperty("--phone-height","390px")');wait()
r=rect('[role=dialog]');check('Bot dialog fits keyboard visible area',r['top']>=0 and r['bottom']<=390)
shot('11-keyboard-new-bot-simulation.png')

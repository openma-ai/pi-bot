js('window.dispatchEvent(new Event("resize"))');click('返回会话列表');click('设置')
click('默认模型','combobox');click('Pibo Fast · 测试模型','option')
js('(()=>{const b=[...document.querySelectorAll("button")].find(e=>e.textContent.includes("保存更改"));b.click();b.click()})()');wait()
check('Double click saves model once',js('window.__PIBO_TEST__.modelWrites.length')==1)
check('Model persisted in mock',js('window.__PIBO_TEST__.modelWrites[0].model')=='pibo-fast')
shot('12-model-saved-phone.png')
